#!/usr/bin/env python3
"""Render docs/self-regulating-storage/whitepaper.md into the 0x0 frontend's
/whitepaper view (frontends/0x0/views/whitepaper.html). Rerun after editing
the markdown. Needs python3-markdown.

  python3 tools/build-whitepaper-page.py
"""
import html
import os
import re

import markdown

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "self-regulating-storage", "whitepaper.md")
OUT = os.path.join(ROOT, "frontends", "0x0", "views", "whitepaper.html")

md = open(SRC, encoding="utf-8").read()
body = markdown.markdown(md, extensions=["tables", "fenced_code", "sane_lists"], output_format="html")
# Go templates would read {{ in the paper as actions; there are none today,
# but keep any that appear literal.
body = body.replace("{{", "{{`{{`}}")
# Bare reference URLs become links.
body = re.sub(r'(?<![">])(https?://[^\s<)]+)', lambda m: f'<a href="{m.group(1)}" target="_blank" rel="noopener">{html.escape(m.group(1))}</a>', body)

page = '''{{define "title"}}{{template "protocolName"}} whitepaper{{end}}

{{define "view"}}
<!-- Generated by tools/build-whitepaper-page.py from
     docs/self-regulating-storage/whitepaper.md. Edit the markdown, not this. -->
<style>
  .paper { max-width: 46rem; font-weight: 400; line-height: 1.75; }
  .paper h1 { font-size: clamp(1.6rem, 4vw, 2.4rem); line-height: 1.2; margin: 0.4rem 0 0.6rem; }
  .paper h2 { font-size: 1.15rem; margin: 2.2rem 0 0.6rem; border-top: 1px solid #333; padding-top: 1.4rem; }
  .paper h3 { font-size: 1rem; margin: 1.6rem 0 0.4rem; color: #ddd; }
  .paper p, .paper ul, .paper ol { margin: 0.7rem 0; color: #ccc; }
  .paper ul, .paper ol { padding-left: 1.4rem; }
  .paper li { margin: 0.25rem 0; }
  .paper strong { color: #fff; }
  .paper hr { display: none; } /* section headings carry their own rule */
  .paper pre { background: #0d0d0d; border: 1px solid #222; padding: 0.9rem 1rem; overflow-x: auto; font-size: 13px; line-height: 1.5; color: #ddd; margin: 0.9rem 0; }
  .paper code { font-family: inherit; font-size: 0.95em; color: #eee; }
  .paper table { border-collapse: collapse; width: 100%; font-size: 13px; margin: 0.9rem 0; display: block; overflow-x: auto; }
  .paper th, .paper td { border: 1px solid #333; padding: 0.4rem 0.6rem; text-align: left; vertical-align: top; }
  .paper th { color: #fff; }
  .paper a { color: #fff; }
  .crumbs { font-size: 12px; color: #888; margin-bottom: 1.4rem; }
</style>
<p class="crumbs"><a href="/">0x0</a> &nbsp;/&nbsp; {{template "protocolName"}} &nbsp;·&nbsp; <a href="https://github.com/0ceanSlim/lotus/blob/main/docs/self-regulating-storage/whitepaper.md" target="_blank" rel="noopener">markdown</a> &nbsp;·&nbsp; <a href="https://github.com/0ceanSlim/lotus/blob/main/docs/self-regulating-storage/sim.py" target="_blank" rel="noopener">simulation</a></p>
<article class="paper">
''' + body + '''
</article>
{{end}}
'''
open(OUT, "w", encoding="utf-8").write(page)
print("wrote", os.path.relpath(OUT, ROOT), len(page), "bytes")
